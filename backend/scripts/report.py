"""Generate docs/RESULTS.md from stored evaluations (no hand-typed numbers).

Usage: python scripts/report.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from app import config  # noqa: E402
from app.db import models as db  # noqa: E402
from app.inference import service  # noqa: E402
from app.training import registry  # noqa: E402


def f(v, d=3):
    return "—" if v is None else f"{v:.{d}f}"


def p(v, d=1):
    return "—" if v is None else f"{v * 100:.{d}f}%"


def main() -> None:
    registry.import_all()
    active = service.active_experiment_id()
    sel_path = config.MODELS_DIR / "selection.json"
    selection = json.loads(sel_path.read_text()) if sel_path.exists() else None
    L = ["# Results", "",
         "_Generated by `backend/scripts/report.py` from the stored evaluations in the experiment database. "
         "Every number below was computed by the code from real MIT-BIH beats._", "",
         "> Research-model results on a 1970s research database. They do not establish clinical validity. "
         "See [LIMITATIONS.md](LIMITATIONS.md).", ""]
    with db.session() as s:
        exps = s.query(db.Experiment).filter_by(status="completed").order_by(db.Experiment.created_at).all()
        L += ["## 1. All experiments (validation subjects, fold 2: records 116, 124, 201, 202, 203, 205)", "",
              "| Experiment | Type | Val macro-F1 | Val F1 N | S | V | F | Train macro-F1 | 5-fold CV macro-F1 |",
              "|---|---|---|---|---|---|---|---|---|"]
        for e in exps:
            sm = e.summary or {}
            pc = sm.get("val_per_class_f1") or {}
            cv = e.cv_results
            cvs = f"{cv['mean_macro_f1']:.3f} ± {cv['std_macro_f1']:.3f}" if cv else "—"
            L.append(f"| {e.name}{' **(selected)**' if e.id == active else ''} | {'1D CNN' if e.kind == 'cnn' else 'baseline'} | "
                     f"{f(sm.get('val_macro_f1'))} | {f(pc.get('N'), 2)} | {f(pc.get('S'), 2)} | {f(pc.get('V'), 2)} | "
                     f"{f(pc.get('F'), 2)} | {f(sm.get('train_macro_f1'))} | {cvs} |")
        L += ["", "The large gap between training and validation macro-F1 shows the central difficulty: "
              "the networks fit training subjects almost perfectly but generalise much less well to new subjects.", ""]
        if selection:
            L += ["## 2. Model selection", "", f"Criterion: {selection['criterion']}. Test subjects used: "
                  f"**{selection['test_subjects_used']}**.", "",
                  "| Candidate | CV macro-F1 (mean ± SD over 5 folds) | Fold-2 validation macro-F1 |", "|---|---|---|"]
            for c in selection["candidates"]:
                L.append(f"| {c['name']} | {c['cv_mean_macro_f1']:.3f} ± {c['cv_std_macro_f1']:.3f} | {f(c['val_macro_f1'])} |")
            L += ["", f"Selected: **{selection['selected']['name']}** (`{selection['selected']['id']}`).", ""]

        tested = [e for e in exps if any(ev.partition == "test" for ev in e.evaluations)]
        L += ["## 3. Held-out test subjects (21 subjects, never used for training or selection)", ""]
        if not tested:
            L += ["No held-out evaluation has been run yet.", ""]
        for e in tested:
            ev = {x.partition: x for x in e.evaluations}["test"]
            m, b = ev.metrics, ev.bootstrap or {}
            ci = lambda k: f"{b[k][0]:.3f}–{b[k][1]:.3f}" if k in b else "—"  # noqa: E731
            L += [f"### {e.name} (`{e.id}`)", "",
                  f"- Beats: {m['n']:,} from records {', '.join(ev.records)}",
                  f"- **Macro-F1 {f(m['macro_f1'])}** (95% subject-bootstrap CI {ci('macro_f1')}), weighted F1 {f(m['weighted_f1'])}, "
                  f"accuracy {p(m['accuracy'])}, macro ROC-AUC {f(m.get('macro_roc_auc'))}",
                  f"- Inference: {ev.inference.get('per_beat_ms_batched')} ms/beat batched, "
                  f"{ev.inference.get('single_beat_latency_ms_median', '—')} ms single-beat latency (CPU)", "",
                  "| Class | Support | Sensitivity | +P (precision) | Specificity | F1 | F1 95% CI | ROC-AUC | PR-AP |",
                  "|---|---|---|---|---|---|---|---|---|"]
            for c in m["classes"]:
                pc = m["per_class"][c]
                L.append(f"| {c} | {pc['support']:,} | {p(pc['sensitivity'])} | {p(pc['precision'])} | {p(pc['specificity'])} | "
                         f"{f(pc['f1'])} | {ci(c + '_f1')} | {f(m.get('roc', {}).get(c, {}).get('auc'))} | "
                         f"{f(m.get('pr', {}).get(c, {}).get('ap'))} |")
            L += ["", "Confusion matrix (rows = expert reference, columns = prediction):", "",
                  "| | " + " | ".join(m["classes"]) + " |", "|---" * (len(m["classes"]) + 1) + "|"]
            for c, row in zip(m["classes"], m["confusion_matrix"]):
                L.append(f"| **{c}** | " + " | ".join(f"{v:,}" for v in row) + " |")
            L.append("")
        log = s.query(db.TestAccess).order_by(db.TestAccess.timestamp).all()
        L += ["## 4. Test-set access log", "", "| When (UTC) | Experiment | Purpose |", "|---|---|---|"]
        L += [f"| {t.timestamp:%Y-%m-%d %H:%M} | `{t.experiment_id}` | {t.purpose} |" for t in log] or ["| — | — | — |"]
        L += ["", "## 5. Interpretation", "",
              "- Accuracy is dominated by N beats; macro-F1 and per-class sensitivity and precision are the meaningful figures.",
              "- S and F beats are the hard classes in inter-patient evaluation, as in the published literature. Test S beats are "
              "dominated by one subject (record 232), and training F beats by one subject (record 208).",
              "- Confidence intervals resample patients, so they reflect between-patient variability. They are wide because only 21 test subjects exist.",
              "- The split is the subject-corrected DS1/DS2 protocol (record 202 moved to training), so the numbers are not directly comparable "
              "with papers that used the original split.", ""]
    out = config.ROOT / "docs" / "RESULTS.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
